//! Generates `build.sh` / `build.bat` from the `build` section of each modulo,
//! plus task definitions for VS Code and Zed so "build" works from the editor.
//!
//! prox only *writes* these scripts. The user runs them; prox never does.

use crate::modulo::{BuildSpec, Installed, MergeMode};
use crate::scaffold::{render, write_text, Ctx, Esc, Report};
use anyhow::Result;
use serde_json::json;
use std::fs;
use std::path::Path;

fn fn_id(name: &str) -> String {
    name.chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect()
}

fn lines(cmds: &[String], ctx: &Ctx, indent: &str, eol: &str) -> String {
    cmds.iter()
        .map(|c| format!("{indent}{}{eol}", render(c, ctx, Esc::None)))
        .collect()
}

pub fn sh_script(specs: &[(&str, &BuildSpec)], ctx: &Ctx) -> String {
    let mut s = String::new();
    s.push_str("#!/usr/bin/env bash\n");
    s.push_str(&format!(
        "# Generated by prox {} for \"{}\". Safe to edit.\n",
        env!("CARGO_PKG_VERSION"),
        ctx.name
    ));
    s.push_str("set -euo pipefail\ncd \"$(dirname \"${BASH_SOURCE[0]}\")\"\n\n");
    s.push_str("need() {\n  command -v \"$1\" >/dev/null 2>&1 || { echo \"error: '$1' was not found in PATH\" >&2; exit 1; }\n}\n\n");

    for (name, b) in specs {
        let id = fn_id(name);
        s.push_str(&format!("build_{id}() {{\n"));
        for r in &b.requires {
            s.push_str(&format!("  need {r}\n"));
        }
        s.push_str(&format!("  echo \"==> building {name}\"\n"));
        s.push_str(&lines(&b.build_sh, ctx, "  ", "\n"));
        s.push_str("  :\n}\n\n");
        if !b.run_sh.is_empty() {
            s.push_str(&format!("run_{id}() {{\n"));
            s.push_str(&lines(&b.run_sh, ctx, "  ", "\n"));
            s.push_str("  :\n}\n\n");
        }
        if !b.clean_sh.is_empty() {
            s.push_str(&format!("clean_{id}() {{\n"));
            s.push_str(&lines(&b.clean_sh, ctx, "  ", "\n"));
            s.push_str("  :\n}\n\n");
        }
    }

    let builds: String = specs
        .iter()
        .map(|(n, _)| format!("build_{}; ", fn_id(n)))
        .collect();
    let cleans: String = specs
        .iter()
        .filter(|(_, b)| !b.clean_sh.is_empty())
        .map(|(n, _)| format!("clean_{}; ", fn_id(n)))
        .collect();
    let run = specs
        .iter()
        .find(|(_, b)| !b.run_sh.is_empty())
        .map(|(n, _)| format!("run_{}", fn_id(n)))
        .unwrap_or_else(|| "echo 'nothing to run'".to_string());

    s.push_str("usage() { echo \"usage: $0 [build|run|clean]\"; }\n\n");
    s.push_str("case \"${1:-build}\" in\n");
    s.push_str(&format!("  build) {builds}echo \"==> done\" ;;\n"));
    s.push_str(&format!("  run) {builds}{run} ;;\n"));
    s.push_str(&format!("  clean) {cleans}echo \"==> cleaned\" ;;\n"));
    s.push_str("  -h|--help|help) usage ;;\n");
    s.push_str("  *) usage >&2; exit 1 ;;\nesac\n");
    s
}

pub fn bat_script(specs: &[(&str, &BuildSpec)], ctx: &Ctx) -> String {
    let mut s = String::new();
    s.push_str("@echo off\r\n");
    s.push_str(&format!(
        "rem Generated by prox {} for \"{}\". Safe to edit.\r\n",
        env!("CARGO_PKG_VERSION"),
        ctx.name
    ));
    s.push_str("setlocal enableextensions\r\ncd /d \"%~dp0\"\r\n");
    s.push_str("set \"ACTION=%~1\"\r\nif \"%ACTION%\"==\"\" set \"ACTION=build\"\r\n");
    s.push_str("if /i \"%ACTION%\"==\"build\" goto :do_build\r\n");
    s.push_str("if /i \"%ACTION%\"==\"run\" goto :do_run\r\n");
    s.push_str("if /i \"%ACTION%\"==\"clean\" goto :do_clean\r\n");
    s.push_str("echo usage: build.bat [build^|run^|clean]\r\nexit /b 1\r\n\r\n");

    s.push_str(":do_build\r\n");
    for (n, _) in specs {
        s.push_str(&format!(
            "call :build_{}\r\nif errorlevel 1 exit /b 1\r\n",
            fn_id(n)
        ));
    }
    s.push_str("echo ==^> done\r\nexit /b 0\r\n\r\n");

    let run = specs.iter().find(|(_, b)| !b.run_bat.is_empty());
    s.push_str(":do_run\r\ncall :do_build\r\nif errorlevel 1 exit /b 1\r\n");
    match run {
        Some((n, _)) => s.push_str(&format!(
            "call :run_{}\r\nexit /b %errorlevel%\r\n\r\n",
            fn_id(n)
        )),
        None => s.push_str("echo nothing to run\r\nexit /b 0\r\n\r\n"),
    }

    s.push_str(":do_clean\r\n");
    for (n, b) in specs {
        if !b.clean_bat.is_empty() {
            s.push_str(&format!("call :clean_{}\r\n", fn_id(n)));
        }
    }
    s.push_str("echo ==^> cleaned\r\nexit /b 0\r\n\r\n");

    for (name, b) in specs {
        let id = fn_id(name);
        s.push_str(&format!(":build_{id}\r\n"));
        if b.build_bat.is_empty() {
            s.push_str(&format!(
                "echo error: building {name} is not supported by this script on Windows 1>&2\r\nexit /b 1\r\n\r\n"
            ));
            continue;
        }
        let reqs = b.requires_bat.as_ref().unwrap_or(&b.requires);
        for r in reqs {
            s.push_str(&format!(
                "where {r} >nul 2>nul\r\nif errorlevel 1 (echo error: {r} was not found in PATH 1>&2 & exit /b 1)\r\n"
            ));
        }
        s.push_str(&format!("echo ==^> building {name}\r\n"));
        s.push_str(&lines(&b.build_bat, ctx, "", "\r\n"));
        s.push_str("exit /b 0\r\n\r\n");
        if !b.run_bat.is_empty() {
            s.push_str(&format!(":run_{id}\r\n"));
            s.push_str(&lines(&b.run_bat, ctx, "", "\r\n"));
            s.push_str("exit /b %errorlevel%\r\n\r\n");
        }
        if !b.clean_bat.is_empty() {
            s.push_str(&format!(":clean_{id}\r\n"));
            s.push_str(&lines(&b.clean_bat, ctx, "", "\r\n"));
            s.push_str("exit /b 0\r\n\r\n");
        }
    }
    s
}

pub fn generate(project: &Path, mods: &[Installed], ctx: &Ctx, rep: &mut Report) -> Result<()> {
    let specs: Vec<(&str, &BuildSpec)> = mods
        .iter()
        .filter_map(|m| m.modulo.build.as_ref().map(|b| (m.modulo.name.as_str(), b)))
        .collect();
    if specs.is_empty() {
        return Ok(());
    }

    let sh_path = project.join("build.sh");
    fs::write(&sh_path, sh_script(&specs, ctx))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(&sh_path, fs::Permissions::from_mode(0o755))?;
    }
    rep.written.push("build.sh".into());

    fs::write(project.join("build.bat"), bat_script(&specs, ctx))?;
    rep.written.push("build.bat".into());

    // Editor tasks, so "build" / "run" work from the editor UI.
    let matcher = specs
        .iter()
        .find_map(|(_, b)| b.problem_matcher.clone())
        .map(|m| vec![m])
        .unwrap_or_default();
    let task = |label: &str, action: &str, default: bool| {
        let mut t = json!({
            "label": label,
            "type": "shell",
            "command": "./build.sh",
            "args": [action],
            "windows": { "command": ".\\build.bat" },
            "problemMatcher": matcher,
        });
        if default {
            t["group"] = json!({ "kind": "build", "isDefault": true });
        }
        t
    };
    let vscode = json!({
        "version": "2.0.0",
        "tasks": [task("build", "build", true), task("run", "run", false), task("clean", "clean", false)]
    });
    write_text(
        &project.join(".vscode/tasks.json"),
        ".vscode/tasks.json",
        &vscode.to_string(),
        MergeMode::Json,
        rep,
    )?;

    let zed_task = |label: &str, action: &str| {
        json!({
            "label": label,
            "command": "./build.sh",
            "args": [action],
            "use_new_terminal": false,
            "allow_concurrent_runs": false,
            "reveal": "always"
        })
    };
    let zed = json!([
        zed_task("build", "build"),
        zed_task("run", "run"),
        zed_task("clean", "clean")
    ]);
    write_text(
        &project.join(".zed/tasks.json"),
        ".zed/tasks.json",
        &zed.to_string(),
        MergeMode::Json,
        rep,
    )?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn spec() -> BuildSpec {
        BuildSpec {
            requires: vec!["gcc".into()],
            build_sh: vec!["gcc src/main.c -o build/{{name}}".into()],
            build_bat: vec!["gcc src\\main.c -o build\\{{name}}.exe".into()],
            run_sh: vec!["./build/{{name}}".into()],
            run_bat: vec!["build\\{{name}}.exe".into()],
            clean_sh: vec!["rm -rf build".into()],
            clean_bat: vec!["rmdir /s /q build".into()],
            ..Default::default()
        }
    }

    fn ctx() -> Ctx {
        Ctx {
            name: "demo".into(),
            description: String::new(),
            author: String::new(),
            libs: vec![],
        }
    }

    #[test]
    fn sh_contains_commands_and_dispatch() {
        let b = spec();
        let s = sh_script(&[("c", &b)], &ctx());
        assert!(s.starts_with("#!/usr/bin/env bash"));
        assert!(s.contains("build_c()"));
        assert!(s.contains("need gcc"));
        assert!(s.contains("gcc src/main.c -o build/demo"));
        assert!(s.contains("run) build_c; run_c"));
    }

    #[test]
    fn bat_uses_crlf_and_labels() {
        let b = spec();
        let s = bat_script(&[("c", &b)], &ctx());
        assert!(s.contains("\r\n"));
        assert!(s.contains(":build_c"));
        assert!(s.contains("build\\demo.exe"));
        assert!(!s.replace("\r\n", "").contains('\n'));
    }
}
